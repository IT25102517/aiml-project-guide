const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const ts = require('typescript');
const root = path.resolve(__dirname, '..');
const models = JSON.parse(fs.readFileSync(path.join(root, 'src/lib/guide-content.json'), 'utf8'));
const protocol = JSON.parse(fs.readFileSync(path.join(root, 'src/lib/data-protocol.json'), 'utf8'));
const source = fs.readFileSync(path.join(root, 'src/lib/results.ts'), 'utf8');
const code = ts.transpileModule(source, {compilerOptions: {module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2021, esModuleInterop: true}}).outputText;
const context = {exports: {}, require: name => name === './models-data' ? {models} : protocol};
vm.runInNewContext(code, context);
const {readResult, toCSV, parseCSV} = context.exports;
const results = models.map(m => readResult(fs.readFileSync(path.join(root, '../.review-backups/guide-validation-simple', m.modelId, m.modelId + '_result.csv'), 'utf8')));
assert.equal(results.length, 6);
assert.equal(parseCSV(toCSV(results)).length, 7);
for (const result of results) assert.equal(readResult(toCSV([result])).Variant, result.Variant);
assert.throws(() => readResult(toCSV([{...results[0], Protocol:'cars12-v2-seed42-5fold'}])));
assert.throws(() => readResult(toCSV([{...results[0], Validation_Rows:'1194'}])));
assert.throws(() => readResult(toCSV([{...results[0], Validation_RMSE:'NaN'}])));
assert.throws(() => readResult(toCSV(results)));
console.log('PASS: all six real results, CSV round-trip, old protocol, wrong rows and invalid metrics.');
